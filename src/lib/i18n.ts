/**
 * Replace {name} placeholders in a message string. An unknown key returns the
 * key itself, so a typo surfaces visually rather than rendering as blank.
 */

/**
 * Muscle-group display name. The database stores the canonical lowercase
 * token (0001's check constraint); a custom or unknown value renders as
 * itself rather than as a raw key.
 */
export function muscleLabel(locale: Locale, group: string): string {
  const key = 'muscle.' + group.toLowerCase()
  return messages[locale]?.[key] ?? messages.en[key] ?? group
}

/**
 * Equipment display name, same contract as `muscleLabel`.
 *
 * The column is free-form text seeded from a fuzzy import, so an unknown
 * value renders as itself. A lift labelled "smith machine" is better read
 * back verbatim than swallowed by a fallback.
 */
export function equipmentLabel(locale: Locale, equipment: string): string {
  if (!equipment) return ''
  const key = 'equipment.' + equipment.toLowerCase()
  return messages[locale]?.[key] ?? messages.en[key] ?? equipment
}

export function t(
  locale: Locale,
  key: string,
  params?: Record<string, string>,
): string {
  let msg = messages[locale]?.[key] ?? messages.en[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      msg = msg.replace(new RegExp(`\\{${name}\\}`, 'g'), value)
    }
  }
  return msg
}

/**
 * Resolve the initial locale without any side effects.
 *
 * Resolution order (from the Stage 5 spec):
 *  1. A valid stored preference wins.
 *  2. navigator.language whose primary subtag is "ar" gives "ar".
 *  3. "en" as the fallback.
 */
export function resolveInitialLocale(
  stored: string | null,
  navigatorLanguage: string,
): Locale {
  if (stored === 'en' || stored === 'ar') return stored
  const primary = navigatorLanguage.split('-')[0]?.toLowerCase()
  return primary === 'ar' ? 'ar' : 'en'
}
